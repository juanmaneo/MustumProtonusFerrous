/// How `dlls/hal/hal.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through [`crate::wine_spec_unimplemented_stub`].
    Stub,
    /// A function defined in `dlls/hal/hal.c`.
    Function,
    /// A forward to `module.name` in another DLL. `hal.c` does not define these.
    Forward(&'static str),
}

