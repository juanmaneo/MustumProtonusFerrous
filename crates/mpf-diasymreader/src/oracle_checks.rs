fn hex(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

#[test]
fn oracle_get_debug_info_rows() {
    for row in ROWS {
        let mut filename = [0u16; MAX_PATH];
        filename[..row.path.len()].copy_from_slice(row.path);
        let pdb = PdbInfo {
            guid: row.guid,
            age: row.age,
            filename,
        };
        let mut buf = vec![0xaau8; row.cdata.unwrap_or(0)];
        let data = row.cdata.map(|_| buf.as_mut_slice());
        let info = get_debug_info(&pdb, data);
        assert_eq!(info.status.is_ok(), row.ok, "{}", row.name);
        assert_eq!(info.size, row.size, "{}", row.name);
        assert_eq!(info.directory.kind, row.dir_type, "{}", row.name);
        assert_eq!(info.directory.size_of_data, row.dir_size, "{}", row.name);
        if row.cdata.is_some() {
            assert_eq!(buf, hex(row.buf), "{}", row.name);
        }
    }
}
