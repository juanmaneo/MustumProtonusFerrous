/// How `dlls/winmm/winmm.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `@ stdcall`: a real function in the reference. Only the functions listed in `lib.rs` are
    /// ported.
    Stdcall,
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through [`crate::wine_spec_unimplemented_stub`].
    Stub,
}

/// The name of an export. An unnamed entry, such as ordinal 2 (`PlaySoundA`), has only an ordinal.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportName {
    Named(&'static str),
    Ordinal(u16),
}

