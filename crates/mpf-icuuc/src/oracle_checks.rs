#[test]
fn oracle_export_rows() {
    assert_eq!(EXPORTS.len(), ORACLE_ROWS.len());
    for (name, kind, args, target) in ORACLE_ROWS {
        let export = find_export(name).expect("oracle name is exported");
        assert_eq!(export.kind, kind, "{name}");
        assert_eq!(export.args, args, "{name}");
        let (module, function) = forward_target(name).expect("oracle name forwards");
        assert_eq!(format!("{module}.{function}"), target, "{name}");
    }
}
