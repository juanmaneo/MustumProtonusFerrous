/// The `Export` for `name`, or `None` when the spec does not export it. Names are case-sensitive.
pub fn find_export(name: &str) -> Option<&'static Export> {
    EXPORTS.iter().find(|export| export.name == name)
}

/// The forwarder for `name` as `(module, function)`, or `None` when the spec does not export it.
pub fn forward_target(name: &str) -> Option<(&'static str, &'static str)> {
    find_export(name).map(|export| (FORWARD_MODULE, export.name))
}
