/// How `dlls/icuuc/icuuc.spec` declares an export.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `@ cdecl`: a `__cdecl` function.
    Cdecl,
    /// `@ varargs`: like `cdecl`, but with a variable argument list. winebuild sets
    /// `FLAG_NORELAY` on it, since relay debugging is not possible for a varargs entry point.
    Varargs,
}

/// One `@` line of `icuuc.spec`: the exported name, how it is declared, and its argument types
/// as the spec writes them (`ptr`, `str`, `wstr` or `long`), in order.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Export {
    pub name: &'static str,
    pub kind: ExportKind,
    pub args: &'static str,
}

