/// Returns the kind of `name`, or `None` if it is not exported.
pub fn export_kind(name: &str) -> Option<ExportKind> {
    EXPORTS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, kind)| *kind)
}
