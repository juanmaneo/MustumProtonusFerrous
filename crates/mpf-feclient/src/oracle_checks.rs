#[test]
fn oracle_stub_rows() {
    for (index, (helper, code, flags, number_parameters, module, function)) in
        ORACLE_ROWS.into_iter().enumerate()
    {
        assert_eq!(EXPORTS[index], function, "row {:02}", index + 1);
        assert_eq!(
            helper(),
            StubException {
                code,
                flags,
                number_parameters,
                module,
                function,
            },
            "row {:02}",
            index + 1
        );
    }
}
