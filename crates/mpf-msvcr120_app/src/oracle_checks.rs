fn arch_tokens(arch: &[Arch]) -> String {
    arch.iter().map(|a| a.token()).collect::<Vec<_>>().join(",")
}

#[test]
fn oracle_stub_rows() {
    for (helper, code, flags, number_parameters, module, function) in STUB_ROWS {
        assert_eq!(
            helper(),
            StubException {
                code,
                flags,
                number_parameters,
                module,
                function,
            }
        );
    }
}

#[test]
fn oracle_stub_rows_are_stub_exports() {
    for (_, _, _, _, _, function) in STUB_ROWS {
        assert_eq!(
            find_export(function).map(|e| e.kind),
            Some(ExportKind::Stub)
        );
    }
}

#[test]
fn oracle_export_rows() {
    assert_eq!(EXPORTS.len(), EXPORT_ROWS.len());
    for (export, (name, arch, kind, private)) in EXPORTS.iter().zip(EXPORT_ROWS) {
        assert_eq!(export.name, name);
        assert_eq!(arch_tokens(export.arch), arch);
        assert_eq!(export.kind, kind);
        assert_eq!(export.private, private);
    }
}

#[test]
fn oracle_export_counts() {
    assert_eq!(EXPORTS.len(), 2158);
    assert_eq!(
        EXPORTS
            .iter()
            .filter(|e| e.kind == ExportKind::Stub)
            .count(),
        400
    );
    assert_eq!(
        EXPORTS
            .iter()
            .filter(|e| e.kind == ExportKind::Forward)
            .count(),
        1758
    );
    assert_eq!(EXPORTS.iter().filter(|e| e.private).count(), 2);
    assert_eq!(
        EXPORTS
            .iter()
            .filter(|e| e.kind == ExportKind::Stub && e.arch.is_empty())
            .count(),
        157
    );
}
