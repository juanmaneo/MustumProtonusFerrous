//! The libusb transfer status to USBD status map of `usbd_status_from_libusb`.

/// `LIBUSB_TRANSFER_COMPLETED`.
const LIBUSB_TRANSFER_COMPLETED: i32 = 0;
/// `LIBUSB_TRANSFER_TIMED_OUT`.
const LIBUSB_TRANSFER_TIMED_OUT: i32 = 2;
/// `LIBUSB_TRANSFER_CANCELLED`.
const LIBUSB_TRANSFER_CANCELLED: i32 = 3;
/// `LIBUSB_TRANSFER_STALL`.
const LIBUSB_TRANSFER_STALL: i32 = 4;
/// `LIBUSB_TRANSFER_NO_DEVICE`.
const LIBUSB_TRANSFER_NO_DEVICE: i32 = 5;

/// `USBD_STATUS_SUCCESS`.
const USBD_STATUS_SUCCESS: i32 = 0;
/// `USBD_STATUS_ENDPOINT_HALTED`.
const USBD_STATUS_ENDPOINT_HALTED: i32 = 0xC000_0030_u32 as i32;
/// `USBD_STATUS_REQUEST_FAILED`.
const USBD_STATUS_REQUEST_FAILED: i32 = 0x8000_0500_u32 as i32;
/// `USBD_STATUS_TIMEOUT`.
const USBD_STATUS_TIMEOUT: i32 = 0xC000_6000_u32 as i32;
/// `USBD_STATUS_DEVICE_GONE`.
const USBD_STATUS_DEVICE_GONE: i32 = 0xC000_7000_u32 as i32;
/// `USBD_STATUS_CANCELED`.
const USBD_STATUS_CANCELED: i32 = 0xC001_0000_u32 as i32;

/// `usbd_status_from_libusb`: the USBD status for a libusb transfer status. Any
/// status without its own case, including `LIBUSB_TRANSFER_ERROR` and
/// `LIBUSB_TRANSFER_OVERFLOW`, gives `USBD_STATUS_REQUEST_FAILED`.
pub fn usbd_status_from_libusb(status: i32) -> i32 {
    match status {
        LIBUSB_TRANSFER_CANCELLED => USBD_STATUS_CANCELED,
        LIBUSB_TRANSFER_COMPLETED => USBD_STATUS_SUCCESS,
        LIBUSB_TRANSFER_NO_DEVICE => USBD_STATUS_DEVICE_GONE,
        LIBUSB_TRANSFER_STALL => USBD_STATUS_ENDPOINT_HALTED,
        LIBUSB_TRANSFER_TIMED_OUT => USBD_STATUS_TIMEOUT,
        _ => USBD_STATUS_REQUEST_FAILED,
    }
}
