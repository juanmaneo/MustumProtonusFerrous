#[test]
fn oracle_stub_rows() {
    for ((name, helper), (export, code, flags, nargs, module, function)) in
        EXPORTS.iter().zip(ORACLE_ROWS)
    {
        assert_eq!(*name, export);
        let expected = StubException {
            code,
            flags,
            number_parameters: nargs,
            module,
            function,
        };
        assert_eq!(helper(), expected);
        assert_eq!(export_stub(export), Some(expected));
    }
}
