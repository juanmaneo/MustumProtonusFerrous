//! Replays of the 25 oracle rows in `target/canon/mfreadwrite`. The oracle compiles the verbatim
//! `reader.c` ranges for stream selection, read index, transform lookup, video-processor policy,
//! stopped state, first stream index and `source_reader_start_source` with
//! `gcc -fsanitize=address,undefined -g`, with the COM and Win32 shims in `wine_mock.h`. It prints
//! one test per row. Each `oracle_oNN` test reproduces row NN, and its expected value is what the C
//! printed for that row. No row trips the sanitizer.

use crate::{
    allow_video_processor, first_stream_index, is_source_stopped, next_selected_stream,
    start_source, stream_read_index, transform_at_index, StreamSlot, StreamState, E_FAIL,
    MF_E_INVALIDREQUEST, MF_E_INVALIDSTREAMNUMBER, MF_E_MEDIA_SOURCE_NO_STREAMS_SELECTED,
    MF_MEDIA_TYPE_AUDIO, MF_MEDIA_TYPE_VIDEO, MF_SOURCE_READER_ANY_STREAM,
    MF_SOURCE_READER_FIRST_AUDIO_STREAM, MF_SOURCE_READER_FIRST_VIDEO_STREAM,
    MF_SOURCE_READER_INVALID_STREAM_INDEX, S_OK,
};

fn st(selected: bool, eos: bool, responses: u32, last_sample_ts: i64) -> StreamState {
    StreamState {
        selected,
        eos,
        responses,
        last_sample_ts,
    }
}

fn slot(has_stream: bool, flags: u32) -> StreamSlot {
    StreamSlot { has_stream, flags }
}

/// `Start` for a source that was stopped, so the C passes a `VT_I8` position, not `VT_EMPTY`.
fn start_for_stopped_source(position_empty: bool) -> crate::Hresult {
    assert!(!position_empty);
    S_OK
}

/// `Start` for a source that was already started, which the mock makes fail with `E_FAIL`.
fn start_for_started_source_fails(position_empty: bool) -> crate::Hresult {
    assert!(position_empty);
    E_FAIL
}
