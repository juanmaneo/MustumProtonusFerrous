/// How `dlls/setupapi/setupapi.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `@ stdcall` with no target: a function of `setupapi.dll`. Only the 22 fixed-value
    /// functions have code in this crate.
    Stdcall,
    /// `@ stdcall` with a local target: the name is another name for the function `target`.
    Alias(&'static str),
    /// `@ stdcall` with a `dll.function` target: the call is forwarded to another DLL.
    Forward(&'static str),
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through [`crate::wine_spec_unimplemented_stub`].
    Stub,
}

