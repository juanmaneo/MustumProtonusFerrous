#[test]
fn oracle_stub_rows() {
    for &(stub, code, flags, number_parameters, module, function) in &ORACLE_ROWS {
        let expected = StubException {
            code,
            flags,
            number_parameters,
            module,
            function,
        };
        assert_eq!(stub(), expected, "export {function}");
    }
}

#[test]
fn oracle_rows_follow_spec_order() {
    // Not oracle-derived: checks the rows against the export table, in order.
    assert_eq!(ORACLE_ROWS.len(), EXPORTS.len());
    for (&(_, _, _, _, _, function), export) in ORACLE_ROWS.iter().zip(EXPORTS.iter()) {
        assert_eq!(function, export.name);
    }
}
