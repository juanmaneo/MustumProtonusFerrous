/// How `dlls/shdocvw/shdocvw.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// A C function whose portable logic is ported in this crate.
    Ported,
    /// `stub`: raises `EXCEPTION_WINE_STUB` through [`crate::stub_for_export`].
    Stub,
    /// Forwarded by the spec file to another module, so this DLL has no body for it.
    Forwarded,
    /// A C function whose logic needs the OS, or a name with no definition in the sources.
    NotPorted,
}

