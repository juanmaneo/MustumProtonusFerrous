use super::{next_runtime, Date, DateTime, Trigger};

fn date(year: u16, month: u16, day: u16) -> Date {
    Date { year, month, day }
}

fn time(year: u16, month: u16, day: u16, hour: u16, minute: u16) -> DateTime {
    DateTime {
        date: date(year, month, day),
        hour,
        minute,
        second: 0,
        millisecond: 0,
    }
}

macro_rules! trigger {
    ($trigger_type:expr, $flags:expr, $begin:expr, $end:expr, $start_hour:expr, $start_minute:expr, $daily_days_interval:expr, $weekly_weeks_interval:expr, $weekly_days_of_week:expr $(,)?) => {
        Trigger {
            trigger_type: $trigger_type,
            flags: $flags,
            begin: $begin,
            end: $end,
            start_hour: $start_hour,
            start_minute: $start_minute,
            daily_days_interval: $daily_days_interval,
            weekly_weeks_interval: $weekly_weeks_interval,
            weekly_days_of_week: $weekly_days_of_week,
        }
    };
}

