/// Maps a WLDAP32 code to a Win32 error code, as `LdapMapErrorToWin32` does. Codes past the end
/// of the table map to `ERROR_DS_GENERIC_ERROR`.
pub fn ldap_map_error_to_win32(error: u32) -> u32 {
    match ERRORMAP.get(error as usize) {
        Some(&code) => code,
        None => ERROR_DS_GENERIC_ERROR,
    }
}
