/// Maps an OpenLDAP result code to a WLDAP32 code, as `map_error` does. Unlisted codes pass
/// through, and negative codes wrap to their 32-bit two's complement.
pub fn map_error(error: i32) -> u32 {
    for &(ldap, wldap32) in LDAP_TO_WLDAP32 {
        if ldap == error {
            return wldap32;
        }
    }
    error as u32
}

