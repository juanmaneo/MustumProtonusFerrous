//! Oracle-derived test vectors for the ported wow64cpu logic.
//!
//! The vectors were captured by compiling the verbatim Wine C bodies of
//! `fpux_to_fpu` and `copy_context_64to32` from `dlls/wow64cpu/cpu.c` with
//! `gcc -fsanitize=address,undefined -g` (harness: `target/canon/wow64cpu/harness.c`).
//! The harness printed 25 rows: 17 `FpuxRow` and 8 `CtxRow`.
//!
//! Excluded (4 rows, all flagged by the sanitizers):
//! - two `FpuxRow`s with `ErrorOpcode` bit 15 set (`op` 0x8001 and 0xffff): UBSan reports
//!   `ErrorOpcode << 16` as a left shift of a signed int that does not fit (it reported the
//!   shift once, as both rows share one source location);
//! - two `CtxRow`s with the `CONTEXT_I386_EXTENDED_REGISTERS` bit (flags 0x10020 and 0x1003f):
//!   UBSan reports the store to `ExtendedRegisters` as misaligned for `XSAVE_FORMAT`
//!   (offset 0xcc in `I386_CONTEXT`). Their expectations are not repeated anywhere; the
//!   extended-register copy is covered by the edge checks instead.
//!
//! So 21 rows remain: 15 `FpuxRow` and 6 `CtxRow`.

use super::*;

struct FpuxIn {
    cw: u16,
    sw: u16,
    tag: u8,
    op: u16,
    eo: u32,
    es: u16,
    dp: u32,
    dsel: u16,
    regs: [(u64, i64); 8],
}

/// `out` is `[cw, sw, tag_word, error_offset, error_selector, data_offset, data_selector, cr0_npx_state, fnv1a(register_area)]`.
struct FpuxRow {
    input: FpuxIn,
    out: [u64; 9],
}

/// `words` is `[rax, rbx, rcx, rdx, rsi, rdi, rsp, rbp, rip, eflags, cs, ss, ds, es, dr0, dr1, dr2, dr3, dr6, dr7]`
/// (`eflags` and the segments are truncated to their field width).
/// `out` is the `ctx_words` layout.
struct CtxRow {
    flags: u32,
    fs32: u16,
    ds64: u16,
    words: [u64; 20],
    fpux: FpuxIn,
    out: [u64; 33],
}

const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
const FNV_PRIME: u64 = 0x0000_0100_0000_01b3;

fn fnv1a(bytes: &[u8]) -> u64 {
    bytes.iter().fold(FNV_OFFSET, |h, &b| {
        (h ^ u64::from(b)).wrapping_mul(FNV_PRIME)
    })
}

/// `FXSAVE` image with the reserved and XMM bytes zeroed, as the harness builds it.
fn xsave(input: &FpuxIn) -> XsaveFormat {
    XsaveFormat {
        control_word: input.cw,
        status_word: input.sw,
        tag_word: input.tag,
        reserved1: 0,
        error_opcode: input.op,
        error_offset: input.eo,
        error_selector: input.es,
        reserved2: 0,
        data_offset: input.dp,
        data_selector: input.dsel,
        reserved3: 0,
        mxcsr: 0,
        mxcsr_mask: 0,
        float_registers: input.regs.map(|(low, high)| M128A { low, high }),
        xmm_registers: [M128A { low: 0, high: 0 }; 16],
        reserved4: [0; 96],
    }
}

fn amd64(words: &[u64; 20], fpux: &FpuxIn) -> Amd64Context {
    Amd64Context {
        rax: words[0],
        rbx: words[1],
        rcx: words[2],
        rdx: words[3],
        rsi: words[4],
        rdi: words[5],
        rsp: words[6],
        rbp: words[7],
        rip: words[8],
        eflags: words[9] as u32,
        seg_cs: words[10] as u16,
        seg_ss: words[11] as u16,
        seg_ds: words[12] as u16,
        seg_es: words[13] as u16,
        dr0: words[14],
        dr1: words[15],
        dr2: words[16],
        dr3: words[17],
        dr6: words[18],
        dr7: words[19],
        flt_save: xsave(fpux),
    }
}

/// Fills every field with `0xa5`, so a copy that writes nothing is visible.
