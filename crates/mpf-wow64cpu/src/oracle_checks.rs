fn fpux_out(fpu: &I386FloatingSaveArea) -> [u64; 9] {
    let mut out = [0u64; 9];
    let scalars = [
        fpu.control_word,
        fpu.status_word,
        fpu.tag_word,
        fpu.error_offset,
        fpu.error_selector,
        fpu.data_offset,
        fpu.data_selector,
        fpu.cr0_npx_state,
    ];
    for (dst, src) in out.iter_mut().zip(scalars) {
        *dst = u64::from(src);
    }
    out[8] = fnv1a(&fpu.register_area);
    out
}

/// Same order as the `out` array of `CtxRow`.
fn ctx_words(ctx: &I386Context) -> [u64; 33] {
    let fs = &ctx.float_save;
    let scalars = [
        ctx.context_flags,
        ctx.dr0,
        ctx.dr1,
        ctx.dr2,
        ctx.dr3,
        ctx.dr6,
        ctx.dr7,
        ctx.edi,
        ctx.esi,
        ctx.ebx,
        ctx.edx,
        ctx.ecx,
        ctx.eax,
        ctx.ebp,
        ctx.eip,
        ctx.seg_cs,
        ctx.eflags,
        ctx.esp,
        ctx.seg_ss,
        ctx.seg_ds,
        ctx.seg_es,
        ctx.seg_fs,
        ctx.seg_gs,
        fs.control_word,
        fs.status_word,
        fs.tag_word,
        fs.error_offset,
        fs.error_selector,
        fs.data_offset,
        fs.data_selector,
        fs.cr0_npx_state,
    ];
    let mut out = [0u64; 33];
    for (dst, src) in out.iter_mut().zip(scalars) {
        *dst = u64::from(src);
    }
    out[31] = fnv1a(&fs.register_area);
    out[32] = fnv1a(&ctx.extended_registers);
    out
}

