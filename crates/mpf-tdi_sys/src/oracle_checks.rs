#[test]
fn oracle_stub_rows() {
    for (export, code, flags, number_parameters, module, function) in ORACLE_STUB_ROWS {
        assert_eq!(
            export_stub(export),
            Some(StubException {
                code,
                flags,
                number_parameters,
                module,
                function,
            })
        );
    }
}

#[test]
fn oracle_driver_entry_rows() {
    // DRV|path_set|0x00000000: a valid driver object and path.
    // DRV|path_null|0x00000000: NULL driver and path. The trace line that reads `path` is compiled out.
    assert_eq!(driver_entry(), 0x0000_0000);
    assert_eq!(driver_entry(), 0x0000_0000);
}
