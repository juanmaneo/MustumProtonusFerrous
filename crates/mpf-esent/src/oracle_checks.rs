#[test]
fn oracle_stub_rows() {
    // Every printed row: raised=1 code=0x80000100 flags=0x1 nargs=2 module=esent.dll.
    for (helper, function) in ORACLE_ROWS {
        assert_eq!(
            helper(),
            StubException {
                code: 0x8000_0100,
                flags: 0x01,
                number_parameters: 2,
                module: "esent.dll",
                function,
            }
        );
    }
}

#[test]
fn oracle_rows_follow_the_export_table() {
    let functions = ORACLE_ROWS.map(|(_, function)| function);
    let exported = EXPORTS.map(|(name, _)| name);
    assert_eq!(functions, exported);
}
