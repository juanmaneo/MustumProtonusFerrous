//! Port of the portable logic in Wine's `dlls/adsldp`.
//!
//! Ported:
//! - [`map_ldap_error`] (`ldap.c`): maps an LDAP result code to a Win32 error code.
//! - [`schema::get_schema_type`] (`schema.c`): finds an attribute type by name and maps its
//!   syntax OID to an ADS type.
//! - [`path::parse_ldap_path`] (`adsldp.c`, `parse_path`): splits an `LDAP:` path into host,
//!   port and object.
//!
//! Skipped: the ADS COM objects, LDAP bind and search, schema loading, registry access,
//! VARIANT and BSTR handling, and the `FIXME` stubs. They need a directory server, the
//! registry or COM. `parse_path` returns slices of its input instead of allocated BSTRs, so
//! its out-of-memory failure has no counterpart here.

