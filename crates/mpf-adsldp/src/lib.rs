/// Returns `units` up to its first NUL, as the C string functions read them.
pub(crate) fn cstr(units: &[u16]) -> &[u16] {
    let len = units
        .iter()
        .position(|&unit| unit == 0)
        .unwrap_or(units.len());
    &units[..len]
}

/// Compares two NUL-terminated wide strings with ASCII case folding, as `wcsicmp` does for
/// ASCII names. Letters outside ASCII are compared as they are.
pub(crate) fn icase_cmp(a: &[u16], b: &[u16]) -> Ordering {
    folded(a).cmp(folded(b))
}

fn folded(units: &[u16]) -> impl Iterator<Item = u16> + '_ {
    cstr(units).iter().copied().map(fold)
}

fn fold(unit: u16) -> u16 {
    if matches!(unit, 0x61..=0x7a) {
        unit - 0x20
    } else {
        unit
    }
}

