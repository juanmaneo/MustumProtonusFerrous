#[test]
fn oracle_main_c_rows() {
    // Captured output: ctor returned its input and cleared vtable; dtor left it alone.
    let mut writer = VssWriter { vtable: Some(1) };
    let returned = cvss_writer_default_ctor(&mut writer);
    assert!(std::ptr::eq(returned, &writer));
    assert_eq!(writer, VssWriter { vtable: None });
    cvss_writer_dtor(&mut writer);
    assert_eq!(writer, VssWriter { vtable: None });

    // C rows: Initialize=0, Subscribe(0)=0, Subscribe(UINT32_MAX)=0, Unsubscribe=0.
    assert_eq!(cvss_writer_initialize(&mut writer), 0);
    assert_eq!(cvss_writer_subscribe(&mut writer, 0), 0);
    assert_eq!(cvss_writer_subscribe(&mut writer, u32::MAX), 0);
    assert_eq!(cvss_writer_unsubscribe(&mut writer), 0);
    // C rows: CreateVssBackupComponentsInternal and its public wrapper return E_NOTIMPL.
    assert_eq!(create_vss_backup_components_internal(), 0x8000_4001);
    assert_eq!(create_vss_backup_components(), 0x8000_4001);
}
