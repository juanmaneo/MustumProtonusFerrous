#[test]
fn oracle_stub_exports_match_c_records() {
    assert_eq!(ROWS.len(), STUB_EXPORTS.len());
    for (row, export) in ROWS.iter().zip(STUB_EXPORTS) {
        assert_eq!(row.function, export);
        let actual = d3dx9_29_stub(export);
        assert_eq!(actual.code, row.code, "{} code", row.function);
        assert_eq!(actual.flags, row.flags, "{} flags", row.function);
        assert_eq!(
            actual.number_parameters, row.number_parameters,
            "{} parameter count",
            row.function
        );
        assert_eq!(actual.module, row.module, "{} module", row.function);
        assert_eq!(actual.function, row.function, "{} function", row.function);
    }
}
