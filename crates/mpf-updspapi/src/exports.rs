/// How `dlls/updspapi/updspapi.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `@ stdcall` with no forward target: implemented in `dlls/updspapi/main.c`, ported as
    /// [`crate::upd_sp_set_dynamic_string_a`].
    Implemented,
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through [`crate::wine_spec_unimplemented_stub`].
    Stub,
    /// `@ stdcall` with a `setupapi.<name>` target: forwarded, so this DLL runs no code for it.
    Forward(&'static str),
}

