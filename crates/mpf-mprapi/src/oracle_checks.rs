//! Oracle-derived test vectors for the ported mprapi logic.
//!
//! Vectors were captured by compiling the verbatim Wine C bodies of `MprAdminGetErrorString`,
//! `MprAdminIsServiceRunning` and `MprConfigServerConnect` (`dlls/mprapi/mprapi.c`) and of
//! `__wine_spec_unimplemented_stub` (`dlls/ntdll/exception.c`) with
//! `gcc -fsanitize=address,undefined -g` under `target/canon/mprapi/`, and running the harness.
//! The harness printed 138 rows: 9 for the three explicit functions and 129 for the `@ stub`
//! exports, one row per export. ASan and UBSan reported nothing, so no row was excluded.

use super::*;

/// Calls the out-pointer function with a non-NULL sentinel, which the C body overwrites.
fn error_string_row(mprerror: u32) -> (u32, Option<Vec<u16>>) {
    let mut localstr = Some(vec![0x41]);
    let ret = mpr_admin_get_error_string(mprerror, &mut localstr);
    (ret, localstr)
}

/// Calls the handle out-pointer function with a non-NULL sentinel, which the C body overwrites.
fn config_row(server_name: Option<&[u16]>) -> (u32, Option<usize>) {
    let mut hmprconfig = Some(0x1000);
    let ret = mpr_config_server_connect(server_name, &mut hmprconfig);
    (ret, hmprconfig)
}

#[test]
fn oracle_mpr_admin_get_error_string_rows() {
    // row 01 MprAdminGetErrorString mprerror=0 localstr=sentinel -> ret=317 localstr=NULL
    assert_eq!(error_string_row(0), (317, None));
    // row 02 MprAdminGetErrorString mprerror=1 localstr=sentinel -> ret=317 localstr=NULL
    assert_eq!(error_string_row(1), (317, None));
    // row 03 MprAdminGetErrorString mprerror=317 localstr=sentinel -> ret=317 localstr=NULL
    assert_eq!(error_string_row(317), (317, None));
    // row 04 MprAdminGetErrorString mprerror=4294967295 localstr=sentinel -> ret=317 localstr=NULL
    assert_eq!(error_string_row(0xffff_ffff), (317, None));
}

#[test]
fn oracle_mpr_admin_is_service_running_rows() {
    // row 05 MprAdminIsServiceRunning server=NULL -> ret=0
    assert!(!mpr_admin_is_service_running(None));
    // row 06 MprAdminIsServiceRunning server="" -> ret=0
    assert!(!mpr_admin_is_service_running(Some(&[])));
    // row 07 MprAdminIsServiceRunning server="srv" -> ret=0
    assert!(!mpr_admin_is_service_running(Some(&[0x73, 0x72, 0x76])));
}

#[test]
fn oracle_mpr_config_server_connect_rows() {
    // row 08 MprConfigServerConnect server_name=NULL hmprconfig=sentinel -> ret=50 hmprconfig=NULL
    assert_eq!(config_row(None), (50, None));
    // row 09 MprConfigServerConnect server_name="srv" hmprconfig=sentinel -> ret=50 hmprconfig=NULL
    assert_eq!(config_row(Some(&[0x73, 0x72, 0x76])), (50, None));
}

