#[test]
fn oracle_stub_rows_match_the_export_table() {
    let stubs: Vec<&str> = EXPORTS
        .iter()
        .filter(|(_, kind)| *kind == ExportKind::Stub)
        .map(|(name, _)| *name)
        .collect();
    let rows: Vec<&str> = STUB_ROWS.iter().map(|row| row.5).collect();
    assert_eq!(rows, stubs);
}
