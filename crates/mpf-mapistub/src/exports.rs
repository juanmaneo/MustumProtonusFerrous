/// The kind of the export named `name`, or `None` when the spec does not export it. Names are
/// case-sensitive and keep any `@N` suffix. Ordinal-only exports have no name to look up.
pub fn export_kind(name: &str) -> Option<ExportKind> {
    EXPORTS
        .iter()
        .find(|(_, export, _)| *export == Some(name))
        .map(|&(_, _, kind)| kind)
}
