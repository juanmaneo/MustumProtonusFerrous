/// How `dlls/mapistub/mapistub.spec` exports an entry.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `stub`: raises `EXCEPTION_WINE_STUB` through [`crate::wine_spec_unimplemented_stub`].
    Stub,
    /// `stdcall` with a `module.function` target. Winebuild emits no relay for it
    /// (`tools/winebuild/spec32.c`), and the loader resolves the call in the target DLL.
    Forward(&'static str),
    /// `stdcall -private` with no target. The reference has no body for it, so the port does not
    /// model a result.
    Unbound,
}

