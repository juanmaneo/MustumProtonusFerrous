#[test]
fn oracle_stub_rows() {
    for (row, &(stub, code, flags, number_parameters, module, function)) in
        ORACLE_STUB_ROWS.iter().enumerate()
    {
        assert_eq!(
            stub(),
            StubException {
                code,
                flags,
                number_parameters,
                module,
                function,
            },
            "row {:02}",
            row + 1
        );
    }
}

#[test]
fn oracle_row_names_match_stub_exports() {
    // Not oracle-derived: the rows must cover the `@ stub` entries of the export table, in order.
    let rows: Vec<&str> = ORACLE_STUB_ROWS.iter().map(|row| row.5).collect();
    let stubs: Vec<&str> = EXPORTS
        .iter()
        .filter(|export| export.kind == ExportKind::Stub)
        .map(|export| export.name)
        .collect();
    assert_eq!(rows, stubs);
}
