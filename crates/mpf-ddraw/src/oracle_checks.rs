/// The harness's input generator. Row 0 and row 1 use the identity for source 0, row 2 is zero,
/// and the other entries are small integers in -6..=6.
fn make_matrix(row: u32, source: u32) -> Matrix4x4 {
    let mut v = [0.0f32; 16];
    for (i, slot) in v.iter_mut().enumerate() {
        let i = i as u32;
        *slot = (((row * 11 + source * 7 + i * 3) % 13) as i32 - 6) as f32;
    }
    if (row == 0 && source == 0) || (row == 1 && source == 1) {
        v = [0.0; 16];
        v[0] = 1.0;
        v[5] = 1.0;
        v[10] = 1.0;
        v[15] = 1.0;
    }
    if row == 2 {
        v = [0.0; 16];
    }
    from_array(v)
}

fn from_array(v: [f32; 16]) -> Matrix4x4 {
    Matrix4x4 {
        _11: v[0],
        _12: v[1],
        _13: v[2],
        _14: v[3],
        _21: v[4],
        _22: v[5],
        _23: v[6],
        _24: v[7],
        _31: v[8],
        _32: v[9],
        _33: v[10],
        _34: v[11],
        _41: v[12],
        _42: v[13],
        _43: v[14],
        _44: v[15],
    }
}

fn bits(m: &Matrix4x4) -> String {
    [
        m._11, m._12, m._13, m._14, m._21, m._22, m._23, m._24, m._31, m._32, m._33, m._34, m._41,
        m._42, m._43, m._44,
    ]
    .iter()
    .map(|f| format!("{:08x}", f.to_bits()))
    .collect::<Vec<_>>()
    .join(" ")
}

#[test]
fn oracle_rows_match_wine() {
    for (row, expected) in ROWS.iter().enumerate() {
        let row = row as u32;
        let mut out = Matrix4x4::default();
        multiply_matrix(&mut out, &make_matrix(row, 0), &make_matrix(row, 1));
        assert_eq!(bits(&out), *expected, "row {row}");
    }
}
