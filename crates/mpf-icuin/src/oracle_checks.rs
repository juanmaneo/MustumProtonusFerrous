fn kind_name(kind: ExportKind) -> &'static str {
    match kind {
        ExportKind::Cdecl => "cdecl",
        ExportKind::Varargs => "varargs",
    }
}

#[test]
fn oracle_export_rows() {
    assert_eq!(EXPORTS.len(), ORACLE_EXPORTS.len());
    for (export, row) in EXPORTS.iter().zip(ORACLE_EXPORTS) {
        let fields: Vec<&str> = row.split('|').collect();
        assert_eq!(fields.len(), 5, "{row}");
        assert_eq!(export.name, fields[0]);
        assert_eq!(kind_name(export.kind), fields[1]);
        assert_eq!(export.args, fields[2]);
        assert_eq!(
            forward(export.name),
            Some(Forward {
                module: fields[3],
                function: fields[4],
            })
        );
    }
}

#[test]
fn oracle_summary_and_module() {
    let cdecl = EXPORTS
        .iter()
        .filter(|export| export.kind == ExportKind::Cdecl)
        .count();
    let varargs = EXPORTS
        .iter()
        .filter(|export| export.kind == ExportKind::Varargs)
        .count();
    assert_eq!(
        format!("total={}|cdecl={cdecl}|varargs={varargs}", EXPORTS.len()),
        ORACLE_SUMMARY
    );
    assert_eq!(ICUIN_DLL_NAME, ORACLE_MODULE);
}

#[test]
fn oracle_probes() {
    for (name, expected) in ORACLE_PROBES {
        assert_eq!(
            find_export(name).map(|export| kind_name(export.kind)),
            expected,
            "{name:?}"
        );
    }
}
