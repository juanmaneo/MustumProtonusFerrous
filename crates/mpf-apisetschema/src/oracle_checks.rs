//! Oracle-derived test vectors for the ported apiset logic.
//!
//! Vectors were captured by compiling the verbatim Wine C bodies of `apiset_hash`, `GetToken`, `apiset_add_str`,
//! `parse_spec_apiset` and `output_apiset_section` (`tools/winebuild/parser.c` and `tools/winebuild/spec32.c`)
//! with `gcc -fsanitize=address,undefined -g` under `target/canon/apisetschema/`. The harness printed 22 rows:
//! 4 hash rows, 17 spec rows and the full DLL row. One vector is excluded: the name `nohyphen` (probe mode of the
//! harness). `apiset_hash` reads past the end of a name with no `-`, and ASan reports a global-buffer-overflow
//! there. `edge_checks.rs` covers that case with `SpecError::NoHyphen`.

use super::*;

/// Entries, pool bytes, section size, hash offset and FNV-1a 64 of one spec row.
type Row = (usize, usize, usize, usize, u64);

/// FNV-1a 64 over the section bytes, the checksum the harness prints.
fn fnv1a64(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325, |hash, &byte| {
        (hash ^ u64::from(byte)).wrapping_mul(0x0100_0000_01b3)
    })
}

/// Section header dword `index`, counted from the start of the section.
fn dword(section: &[u8], index: usize) -> usize {
    let at = index * 4;
    u32::from_le_bytes(section[at..at + 4].try_into().unwrap()) as usize
}

fn parse_lines(lines: &[&str]) -> Result<Schema, SpecError> {
    let mut schema = Schema::default();
    for line in lines {
        schema.parse_line(line.as_bytes())?;
    }
    Ok(schema)
}

/// Checks a schema against one row: entries, pool bytes, section size, hash offset (header dword 5) and FNV-1a 64.
fn assert_row(schema: &Schema, row: Row) {
    let (entries, pool, size, hash_pos, fnv) = row;
    let section = schema.section();
    assert_eq!(schema.entries.len(), entries);
    assert_eq!(schema.pool.bytes().len(), pool);
    assert_eq!(section.len(), size);
    assert_eq!(dword(&section, 5), hash_pos);
    assert_eq!(fnv1a64(&section), fnv);
}

