// Full DLL: every record of apisetschema.spec, in spec order.
pub const DLL_ROW: Row = (672, 24025, 83024, 77648, 0x9ecdeb88a66903e4);

#[test]
fn oracle_hash_rows() {
    for &(name, hash, hash_len) in HASH_ROWS {
        assert_eq!(
            apiset_hash(name.as_bytes()),
            Some((hash, hash_len)),
            "{name}"
        );
    }
}

#[test]
fn oracle_spec_rows() {
    for &(lines, expected) in SPEC_ROWS {
        let result = parse_lines(lines);
        let Some(row) = expected else {
            assert!(result.is_err(), "{lines:?} should be rejected");
            continue;
        };
        let schema = result.expect("row should parse");
        assert_row(&schema, row);
    }
}

#[test]
fn oracle_full_dll_row() {
    assert_row(&apisetschema(), DLL_ROW);
}
