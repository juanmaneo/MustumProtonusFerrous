/// An argument type in a `.spec` signature, sized as `winebuild` sizes it on i386.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ArgKind {
    Ptr,
    Long,
    Float,
    Wstr,
    Int128,
}

impl ArgKind {
    /// The bytes the argument takes on the i386 stack.
    fn i386_bytes(self) -> u32 {
        match self {
            ArgKind::Int128 => 16,
            ArgKind::Ptr | ArgKind::Long | ArgKind::Float | ArgKind::Wstr => 4,
        }
    }
}

/// How `dlls/gdiplus/gdiplus.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `@ stdcall`: a real function with the argument types in its signature.
    Stdcall(&'static [ArgKind]),
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through the helper of the same snake_case name in `stub.rs`.
    Stub,
}

/// One line of `dlls/gdiplus/gdiplus.spec`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Export {
    pub ordinal: u16,
    pub name: &'static str,
    pub kind: ExportKind,
}

impl Export {
    /// The argument bytes of the `@N` decoration of an i386 `stdcall` export. `None` for stubs,
    /// which have no signature in the spec.
    pub fn stdcall_bytes(&self) -> Option<u32> {
        match self.kind {
            ExportKind::Stdcall(args) => Some(args.iter().map(|arg| arg.i386_bytes()).sum()),
            ExportKind::Stub => None,
        }
    }
}

