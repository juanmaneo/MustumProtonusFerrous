//! Oracle-derived test vectors for the ported gdiplus logic.
//!
//! Vectors were captured by compiling the verbatim Wine C bodies from `dlls/gdiplus` (the
//! `gdiplus.c` helpers, `gdiplus_private.h` inline helpers, `matrix.c`, the explicit
//! `NotImplemented` functions) and `__wine_spec_unimplemented_stub` from
//! `dlls/ntdll/exception.c` with `gcc -fsanitize=address,undefined` under
//! `target/canon/gdiplus/` (`gen_oracle.py`). The harness printed 389 rows; 28 of them are excluded.
//!
//! Excluded rows are `color_over` and `color_over_fgpremult` calls whose computed alpha is
//! 0x80 or more: `a << 24` overflows the C `int` (undefined behaviour). UBSan reports each
//! source site once, so the generator re-runs every such row alone under UBSan to decide.
//! Their expected values are pinned in `edge_checks.rs` instead.

#![allow(clippy::approx_constant, clippy::type_complexity)]

use super::*;

fn bits<const N: usize>(v: [f32; N]) -> [u32; N] {
    v.map(f32::to_bits)
}

fn allocator(ok: bool) -> fn(usize) -> bool {
    if ok {
        |_| true
    } else {
        |_| false
    }
}

fn coords(v: &[[f32; 2]]) -> Vec<[u32; 2]> {
    v.iter().map(|&c| bits(c)).collect()
}

fn point_coords(v: &[PointF]) -> Vec<[u32; 2]> {
    v.iter().map(|p| bits([p.x, p.y])).collect()
}

fn point_coords_i(v: &[Point]) -> Vec<[i32; 2]> {
    v.iter().map(|p| [p.x, p.y]).collect()
}

fn to_point(c: [f32; 2]) -> PointF {
    PointF { x: c[0], y: c[1] }
}

fn to_points(v: &[[f32; 2]]) -> Vec<PointF> {
    v.iter().map(|&c| to_point(c)).collect()
}

fn to_points3(v: [[f32; 2]; 3]) -> [PointF; 3] {
    v.map(to_point)
}

fn to_points_i(v: &[[i32; 2]]) -> Vec<Point> {
    v.iter().map(|&[x, y]| Point { x, y }).collect()
}

fn to_points3_i(v: [[i32; 2]; 3]) -> [Point; 3] {
    v.map(|[x, y]| Point { x, y })
}

fn to_rect(v: [f32; 4]) -> RectF {
    RectF {
        x: v[0],
        y: v[1],
        width: v[2],
        height: v[3],
    }
}

fn to_rect_i(v: [i32; 4]) -> Rect {
    Rect {
        x: v[0],
        y: v[1],
        width: v[2],
        height: v[3],
    }
}

fn to_matrix(elements: Option<[f32; 6]>) -> Option<Matrix> {
    elements.map(|elements| Matrix { elements })
}

fn outcome(result: Result<[f32; 6], Status>) -> (Status, [u32; 6]) {
    match result {
        Ok(elements) => (Status::Ok, bits(elements)),
        Err(status) => (status, [0; 6]),
    }
}

fn flag(result: Result<bool, Status>) -> (Status, bool) {
    match result {
        Ok(value) => (Status::Ok, value),
        Err(status) => (status, false),
    }
}

fn in_place(
    elements: Option<[f32; 6]>,
    op: impl FnOnce(Option<&mut Matrix>) -> Status,
) -> (Status, [u32; 6]) {
    let mut matrix = to_matrix(elements);
    let status = op(matrix.as_mut());
    (status, matrix.map_or([0; 6], |mat| bits(mat.elements)))
}

