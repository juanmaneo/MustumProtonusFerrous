/// The `RaiseException` call made by `__wine_spec_unimplemented_stub`. The stub never
/// returns: it loops on this call.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StubException {
    pub code: u32,
    pub flags: u32,
    pub module: &'static str,
    pub function: &'static str,
}

/// `__wine_spec_unimplemented_stub` from `libs/winecrt0/stub.c`, modelled as the exception it
/// raises. The Rust model returns that exception instead of looping forever.
pub fn unimplemented_stub(module: &'static str, function: &'static str) -> StubException {
    StubException {
        code: EXCEPTION_WINE_STUB,
        flags: EXCEPTION_NONCONTINUABLE,
        module,
        function,
    }
}
