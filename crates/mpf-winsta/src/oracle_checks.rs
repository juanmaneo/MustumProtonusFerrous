#[test]
fn oracle_stub_rows() {
    assert_eq!(STUB_ROWS.len(), 87);
    for &(name, code, flags, number_parameters, module, function) in STUB_ROWS {
        let (_, helper) = STUB_EXPORTS
            .iter()
            .find(|(n, _)| *n == name)
            .expect("every oracle stub row has a helper");
        assert_eq!(
            helper(),
            StubException {
                code,
                flags,
                number_parameters,
                module,
                function,
            }
        );
    }
}

#[test]
fn oracle_explicit_rows() {
    // E WinStationQueryInformationA ret=0 last_error=120 out=77
    let mut w = Winsta::default();
    let mut ret_len = 77;
    assert_eq!(
        w.win_station_query_information_a(0x1, 1, 8, 0x4, 4, Some(&mut ret_len)),
        0
    );
    assert_eq!(w.last_error(), 120);
    assert_eq!(ret_len, 77);

    // E WinStationQueryInformationW ret=0 last_error=120 out=77
    let mut w = Winsta::default();
    let mut ret_len = 77;
    assert_eq!(
        w.win_station_query_information_w(0x1, 1, 8, 0x4, 4, Some(&mut ret_len)),
        0
    );
    assert_eq!(w.last_error(), 120);
    assert_eq!(ret_len, 77);

    // E WinStationRegisterConsoleNotification ret=0 last_error=120 out=-
    let mut w = Winsta::default();
    assert_eq!(
        w.win_station_register_console_notification(0x1, 0x2, 0x3),
        0
    );
    assert_eq!(w.last_error(), 120);

    // E WinStationUnRegisterConsoleNotification ret=0 last_error=120 out=-
    let mut w = Winsta::default();
    assert_eq!(w.win_station_un_register_console_notification(0x1, 0x2), 0);
    assert_eq!(w.last_error(), 120);

    // E WinStationGetAllProcesses ret=0 last_error=120 out=0
    let mut w = Winsta::default();
    let mut process_count = 77;
    assert_eq!(
        w.win_station_get_all_processes(0x1, 2, &mut process_count, 0),
        0
    );
    assert_eq!(w.last_error(), 120);
    assert_eq!(process_count, 0);

    // E WinStationGetProcessSid ret=0 last_error=120 out=77
    // FILETIME { dwLowDateTime: 1, dwHighDateTime: 2 } packed as (high << 32) | low.
    let mut w = Winsta::default();
    let mut sid_size = 77;
    assert_eq!(
        w.win_station_get_process_sid(0x1, 1234, 0x0000_0002_0000_0001, 0x5, Some(&mut sid_size)),
        0
    );
    assert_eq!(w.last_error(), 120);
    assert_eq!(sid_size, 77);

    // E WinStationVirtualOpen ret=0 last_error=120 out=-
    let mut w = Winsta::default();
    assert_eq!(w.win_station_virtual_open(0x1, 0x2, 0x3), 0);
    assert_eq!(w.last_error(), 120);

    // E WinStationEnumerateW ret=0 last_error=120 out=77
    let mut w = Winsta::default();
    let mut count = 77;
    assert_eq!(w.win_station_enumerate_w(0x1, 0x2, Some(&mut count)), 0);
    assert_eq!(w.last_error(), 120);
    assert_eq!(count, 77);
}
