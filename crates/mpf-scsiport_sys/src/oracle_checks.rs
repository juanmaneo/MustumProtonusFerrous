#[test]
fn oracle_stub_rows() {
    for (i, &(export, code, flags, number_parameters, module, function)) in
        ORACLE_STUB_ROWS.iter().enumerate()
    {
        assert_eq!(EXPORTS[i].0, export, "row {}", i + 1);
        assert_eq!(
            export_stub(export),
            Some(StubException {
                code,
                flags,
                number_parameters,
                module,
                function,
            }),
            "row {}",
            i + 1
        );
    }
}

#[test]
fn oracle_driver_entry_rows() {
    // Rows 49-51 of the harness: driver=NULL path=NULL, driver=set path=NULL and
    // driver=set path=set all return status 0x00000000. The port takes no arguments, so one
    // assertion covers all three.
    assert_eq!(driver_entry(), STATUS_SUCCESS);
    assert_eq!(STATUS_SUCCESS, 0x0000_0000);
}
