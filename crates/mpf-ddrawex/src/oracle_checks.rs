//! Oracle-derived vectors for `ddsd_to_ddsd2` and `ddsd2_to_ddsd`.
//!
//! The rows were printed by `target/canon/ddrawex/harness`, which compiles the verbatim
//! Wine bodies of `DDSD_to_DDSD2` and `DDSD2_to_DDSD` from `dlls/ddrawex/ddraw.c` with
//! `gcc -m32 -fsanitize=address,undefined -g`. The shims are the `ddraw.h` structs and
//! `DDSD_*` flags copied verbatim, plus `WARN` as a no-op. There are 24 rows, 12 per
//! function. ASan and UBSan flagged none, so no vectors were excluded.
//!
//! Each row is `(input, output)`, each 26 words in this order: `dwSize`, `dwFlags`,
//! `dwHeight`, `dwWidth`, `lPitch`/`dwLinearSize`, `dwBackBufferCount`, `dwMipMapCount`,
//! `dwAlphaBitDepth`, `lpSurface`, `ddckCKDestOverlay` (low, high), `ddckCKDestBlt`,
//! `ddckCKSrcOverlay`, `ddckCKSrcBlt`, `ddpfPixelFormat` (8 words), `ddsCaps.dwCaps`.
//! The first 11 rows of each function use fixed flags; the 12th uses random flags.

use super::*;

/// Builds a `SurfaceDesc` from one oracle row, using the word order above.
fn from_words(w: &[u32; 26]) -> SurfaceDesc {
    let mut pixel_format = [0u32; 8];
    pixel_format.copy_from_slice(&w[17..25]);
    SurfaceDesc {
        size: w[0],
        flags: w[1],
        height: w[2],
        width: w[3],
        pitch_or_linear_size: w[4],
        back_buffer_count: w[5],
        mip_map_count: w[6],
        alpha_bit_depth: w[7],
        surface: w[8] as usize,
        ck_dest_overlay: ColorKey {
            low: w[9],
            high: w[10],
        },
        ck_dest_blt: ColorKey {
            low: w[11],
            high: w[12],
        },
        ck_src_overlay: ColorKey {
            low: w[13],
            high: w[14],
        },
        ck_src_blt: ColorKey {
            low: w[15],
            high: w[16],
        },
        pixel_format,
        caps: w[25],
    }
}
