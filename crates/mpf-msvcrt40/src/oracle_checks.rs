/// One row per `@ stub` export in spec order: the helper and the `StubException` fields the C
/// harness recorded.
const ORACLE_STUBS: [StubRow; 2] = [
    (iostream_init_vector_deleting_dtor, "code=0x80000100|flags=0x1|nargs=2|module=msvcrt40.dll|function=??_EIostream_init@@QAEPAXI@Z"),
    (iostream_init_scalar_deleting_dtor, "code=0x80000100|flags=0x1|nargs=2|module=msvcrt40.dll|function=??_GIostream_init@@QAEPAXI@Z"),
];

fn kind_name(kind: ExportKind) -> &'static str {
    match kind {
        ExportKind::Cdecl => "cdecl",
        ExportKind::Extern => "extern",
        ExportKind::Stdcall => "stdcall",
        ExportKind::Stub => "stub",
        ExportKind::Thiscall => "thiscall",
        ExportKind::Varargs => "varargs",
    }
}

#[test]
fn oracle_export_rows() {
    assert_eq!(EXPORTS.len(), ORACLE_EXPORTS.len());
    for (export, row) in EXPORTS.iter().zip(ORACLE_EXPORTS) {
        let fields: Vec<&str> = row.split('|').collect();
        assert_eq!(fields.len(), 4, "{row}");
        assert_eq!(export.name, fields[0]);
        assert_eq!(kind_name(export.kind), fields[1]);
        match forward(export.name) {
            Some(target) => {
                assert_eq!(target.module, fields[2]);
                assert_eq!(target.function, fields[3]);
            }
            None => assert_eq!(fields[2..], ["-", "-"], "{row}"),
        }
    }
}

#[test]
fn oracle_summary_and_module() {
    let count = |kind: ExportKind| EXPORTS.iter().filter(|export| export.kind == kind).count();
    let count_module = |module: &str| {
        EXPORTS
            .iter()
            .filter(|export| export.module == Some(module))
            .count()
    };
    assert_eq!(
        format!(
            "total={}|cdecl={}|extern={}|stdcall={}|stub={}|thiscall={}|varargs={}|msvcirt={}|msvcrt={}",
            EXPORTS.len(),
            count(ExportKind::Cdecl),
            count(ExportKind::Extern),
            count(ExportKind::Stdcall),
            count(ExportKind::Stub),
            count(ExportKind::Thiscall),
            count(ExportKind::Varargs),
            count_module("msvcirt"),
            count_module("msvcrt"),
        ),
        ORACLE_SUMMARY
    );
    assert_eq!(MSVCRT40_DLL_NAME, ORACLE_MODULE);
}

#[test]
fn oracle_probes() {
    for (name, kind, module) in ORACLE_PROBES {
        let got = match find_export(name) {
            Some(export) => (kind_name(export.kind), export.module.unwrap_or("-")),
            None => ("none", "-"),
        };
        assert_eq!((kind, module), got, "{name:?}");
    }
}

#[test]
fn oracle_stub_rows() {
    for (row, &(stub, expected)) in ORACLE_STUBS.iter().enumerate() {
        let record = stub();
        assert_eq!(
            format!(
                "code=0x{:08x}|flags=0x{:x}|nargs={}|module={}|function={}",
                record.code, record.flags, record.number_parameters, record.module, record.function
            ),
            expected,
            "row {:02}",
            row + 1
        );
    }
}

#[test]
fn export_table_stub_entries_are_the_oracle_rows() {
    let table: Vec<&str> = EXPORTS
        .iter()
        .filter(|export| export.kind == ExportKind::Stub)
        .map(|export| export.name)
        .collect();
    let rows: Vec<&str> = ORACLE_STUBS
        .iter()
        .map(|&(stub, _)| stub().function)
        .collect();
    assert_eq!(table, rows);
}
