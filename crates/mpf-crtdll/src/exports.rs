/// How `dlls/crtdll/crtdll.spec` declares an export: the keyword after `@`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `@ cdecl`: a function with the C calling convention. The ported ones are in `math`, `ctype`
    /// and `string`.
    Cdecl,
    /// `@ extern`: a data export, such as `_HUGE_dll` or `_iob`.
    Extern,
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through [`crate::wine_spec_unimplemented_stub`].
    Stub,
    /// `@ varargs`: a variadic function, `TYPE_VARARGS` in `tools/winebuild/build.h`.
    Varargs,
}

