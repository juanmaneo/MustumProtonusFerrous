/// How `dlls/tapi32/tapi32.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// A function that returns a constant and has no other effect.
    Fixed(u32),
    /// A function that returns a constant and writes one out-parameter, ported in [`crate::out_param`].
    FixedOut(u32),
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through [`crate::wine_spec_unimplemented_stub`].
    Stub,
    /// `lineGetCountryA` and `lineGetCountryW`, ported as [`crate::line_get_country`].
    CountryList,
    /// `tapiGetLocationInfoA` and `tapiGetLocationInfoW`, ported as [`crate::tapi_get_location_info_a`]
    /// and [`crate::tapi_get_location_info_w`].
    LocationInfo,
    /// `lineGetTranslateCapsA`, which is not ported. See the `Skipped` list in `lib.rs`.
    Unported,
}

