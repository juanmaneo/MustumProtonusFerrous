/// How `dlls/vcruntime140/vcruntime140.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// A function implemented in this DLL's C sources, with no `@ stub` and no forward. Only the
    /// deterministic ones are ported; see the crate docs.
    Native,
    /// `@ stub`: raises `EXCEPTION_WINE_STUB` through [`crate::stub_for_export`].
    Stub,
    /// Forwarded to `ucrtbase.<name>`. This DLL has no code for it.
    Forward,
}

