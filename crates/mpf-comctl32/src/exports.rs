/// How `dlls/comctl32/comctl32.spec` exports a name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExportKind {
    /// `stdcall`: real code. Its body is ported in this crate when lib.rs lists it under
    /// `Ported:`, and is outside this crate's scope otherwise.
    Stdcall,
    /// `stub`: raises `EXCEPTION_WINE_STUB` through `crate::wine_spec_unimplemented_stub`.
    Stub,
    /// A link target without a dot: the export runs the function `target` of this DLL.
    Alias(&'static str),
    /// A link target with a dot, such as `kernelbase.StrChrA`: the export forwards to that DLL.
    Forward(&'static str),
}

/// One non-comment line of `dlls/comctl32/comctl32.spec`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Export {
    /// The ordinal, or `None` for `@` entries.
    pub ordinal: Option<u16>,
    /// The name the DLL exports by name, or `None` for `-noname` entries.
    pub name: Option<&'static str>,
    /// The spec's function name, even for `-noname` entries. winebuild passes it to stubs.
    pub symbol: &'static str,
    pub kind: ExportKind,
}

