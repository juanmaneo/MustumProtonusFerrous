/// The kind of the export `name`, or `None` when the DLL does not export that name.
/// Names are case-sensitive. `-noname` entries are not found by name.
pub fn export_kind(name: &str) -> Option<ExportKind> {
    EXPORTS
        .iter()
        .find(|e| e.name == Some(name))
        .map(|e| e.kind)
}

/// The export with `ordinal`, or `None` when the spec has no such ordinal.
pub fn export_by_ordinal(ordinal: u16) -> Option<Export> {
    EXPORTS.iter().find(|e| e.ordinal == Some(ordinal)).copied()
}
