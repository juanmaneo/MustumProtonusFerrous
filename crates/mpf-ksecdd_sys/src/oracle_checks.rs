#[test]
fn oracle_driver_entry_rows() {
    // row 01 DriverEntry driver=obj path=buffer -> status=0x00000000
    assert_eq!(driver_entry(), 0x0000_0000);
    // row 02 DriverEntry driver=NULL path=NULL -> status=0x00000000
    assert_eq!(driver_entry(), 0x0000_0000);
    // row 03 DriverEntry driver=obj path=NULL -> status=0x00000000
    assert_eq!(driver_entry(), 0x0000_0000);
    // row 04 DriverEntry driver=NULL path=null_buffer -> status=0x00000000
    assert_eq!(driver_entry(), 0x0000_0000);
}

#[test]
fn oracle_stub_rows() {
    for (row, &(helper, function, code, flags, number_parameters, module)) in
        STUB_ROWS.iter().enumerate()
    {
        assert_eq!(
            helper(),
            StubException {
                code,
                flags,
                number_parameters,
                module,
                function,
            },
            "row {:02}",
            row + 5
        );
    }
}
