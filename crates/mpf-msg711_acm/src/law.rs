const SEG_AEND: [i32; 8] = [0x1F, 0x3F, 0x7F, 0xFF, 0x1FF, 0x3FF, 0x7FF, 0xFFF];
const SEG_UEND: [i32; 8] = [0x3F, 0x7F, 0xFF, 0x1FF, 0x3FF, 0x7FF, 0xFFF, 0x1FFF];
const CLIP: i32 = 8159;
const BIAS: i32 = 0x84;

/// Wine's `search`: the first segment whose end is not below `val`, or the
/// table length when `val` is above them all.
fn search(val: i32, table: &[i32; 8]) -> usize {
    table
        .iter()
        .position(|&end| val <= end)
        .unwrap_or(table.len())
}

/// `alaw2linear`: A-law byte to 16-bit linear sample.
pub fn alaw2linear(a_val: u8) -> i16 {
    A2L[usize::from(a_val)] as i16
}

/// `ulaw2linear`: mu-law byte to 16-bit linear sample.
pub fn ulaw2linear(u_val: u8) -> i16 {
    U2L[usize::from(u_val)] as i16
}

/// `linear2alaw`: 16-bit linear sample, passed as `int`, to A-law byte.
pub fn linear2alaw(pcm_val: i32) -> u8 {
    let scaled = pcm_val >> 3;
    let (mask, magnitude) = if scaled >= 0 {
        (0xD5, scaled)
    } else {
        (0x55, -scaled - 1)
    };
    let seg = search(magnitude, &SEG_AEND);
    if seg >= 8 {
        return (0x7F ^ mask) as u8;
    }
    let shift = if seg < 2 { 1 } else { seg };
    let aval = ((seg as i32) << 4) | ((magnitude >> shift) & 0xF);
    (aval ^ mask) as u8
}

/// `linear2ulaw`: 16-bit linear sample to mu-law byte.
pub fn linear2ulaw(pcm_val: i16) -> u8 {
    let scaled = i32::from(pcm_val) >> 2;
    let (mask, magnitude) = if scaled < 0 {
        (0x7F, -scaled)
    } else {
        (0xFF, scaled)
    };
    let magnitude = magnitude.min(CLIP) + (BIAS >> 2);
    let seg = search(magnitude, &SEG_UEND);
    if seg >= 8 {
        return (0x7F ^ mask) as u8;
    }
    let uval = ((seg as i32) << 4) | ((magnitude >> (seg + 1)) & 0xF);
    (uval ^ mask) as u8
}

/// `alaw2ulaw`: A-law byte to mu-law byte.
pub fn alaw2ulaw(aval: u8) -> u8 {
    if aval & 0x80 != 0 {
        0xFF ^ A2U[usize::from(aval ^ 0xD5)]
    } else {
        0x7F ^ A2U[usize::from(aval ^ 0x55)]
    }
}

/// `ulaw2alaw`: mu-law byte to A-law byte.
pub fn ulaw2alaw(uval: u8) -> u8 {
    if uval & 0x80 != 0 {
        0xD5 ^ U2A[usize::from(0xFF ^ uval)].wrapping_sub(1)
    } else {
        0x55 ^ U2A[usize::from(0x7F ^ uval)].wrapping_sub(1)
    }
}
